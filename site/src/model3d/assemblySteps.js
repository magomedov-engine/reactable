// order — индексы болтов (см. setTighten в engineModel.js):
// головка: 0 перед/−z, 1 зад/−z, 2 зад/+z, 3 перед/+z; крышки: крышка·4 + (0/1 вертикальные, 2/3 горизонтальные)
